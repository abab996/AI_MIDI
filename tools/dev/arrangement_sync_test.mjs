import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import tsBlankSpace from 'ts-blank-space';
const window = {};
vm.runInNewContext(tsBlankSpace(fs.readFileSync('frontend/src/arrangement/sync.ts','utf8')), {window, console, setTimeout, clearTimeout});
const merge = (b,l,r) => window.ArrangementSync.merge(b,l,r);
const copy = x => JSON.parse(JSON.stringify(x));
const base={rev:1,tracks:[{id:'one',name:'Track',source:{itemId:'synth'},clips:[{id:'clip',start:0,notes:[{key:60}]}]}],rack:{items:[{id:'synth',name:'Synth'}]},mixer:{channels:{one:{pan:0,fx:[{slot:0,wet:1,bypass:false}]}}}};
let local=copy(base), remote=copy(base);
local.tracks[0].clips[0].start=2;
local.tracks.push({id:'new',name:'New',clips:[]});
remote.rev=2; remote.tracks[0].name='AI'; remote.mixer.channels.one.pan=0.5;
let result=merge(base,local,remote);
assert.equal(result.conflicts.length,0);
assert.equal(result.value.rev,2);
assert.equal(result.value.tracks[0].name,'AI');
assert.equal(result.value.tracks[0].clips[0].start,2);
assert.equal(result.value.tracks[1].id,'new');
local=copy(base);remote=copy(base); local.tracks[0].name='Local';remote.tracks[0].name='Remote';
result=merge(base,local,remote);assert.ok(result.conflicts.some(x=>x.endsWith('.name')));
local=copy(base);remote=copy(base);local.tracks=[];remote.tracks[0].name='Remote';
assert.ok(merge(base,local,remote).conflicts.length);
local=copy(base);remote=copy(base);local.tracks[0].clips[0].notes.push({key:64});remote.tracks[0].clips[0].notes.push({key:67});
assert.ok(merge(base,local,remote).conflicts.some(x=>x.endsWith('.notes')));
local=copy(base);remote=copy(base);local.mixer.channels.one.fx[0].wet=0.2;remote.mixer.channels.one.fx[0].bypass=true;
result=merge(base,local,remote);assert.equal(result.conflicts.length,0);assert.equal(result.value.mixer.channels.one.fx[0].wet,0.2);assert.equal(result.value.mixer.channels.one.fx[0].bypass,true);
const ordered={tracks:[{id:'a'},{id:'b'},{id:'c'}]};
assert.ok(merge(ordered,{tracks:[{id:'b'},{id:'a'},{id:'c'}]},{tracks:[{id:'a'},{id:'c'},{id:'b'}]}).conflicts.some(x=>x.endsWith('.order')));
console.log('arrangement sync: disjoint edits, new tracks, field/delete/note/order conflicts and FX merge passed');
